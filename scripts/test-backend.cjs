const assert = require('node:assert/strict');
const { createRequire } = require('node:module');
const backend = createRequire(require('node:path').resolve('functions/package.json'));
const { initializeApp } = backend('firebase-admin/app');
const { getFirestore, Timestamp } = backend('firebase-admin/firestore');
if (!process.env.FIRESTORE_EMULATOR_HOST || !process.env.GCLOUD_PROJECT?.startsWith('demo-')) throw new Error('Backend tests require a disposable demo emulator.');
initializeApp({ projectId: process.env.GCLOUD_PROJECT });
const { rebuildCareSummary, collectGardenWeather } = require('../functions/dist/operations.js');
(async () => {
  const db = getFirestore(); const id = 'backend-' + Date.now(); const plant = db.doc(`plants/${id}`);
  await plant.set({ name: 'Disposable', owners: ['test'], status: 'active' });
  await rebuildCareSummary(id); assert.equal((await plant.get()).data().careSummary.watering, null);
  const older = plant.collection('logs').doc('older'); const newer = plant.collection('logs').doc('newer');
  await older.set({ type: 'watering', timestamp: Timestamp.fromMillis(1000), calendarDay: '2026-01-01' });
  await newer.set({ type: 'watering', timestamp: Timestamp.fromMillis(2000), calendarDay: '2026-01-02' });
  await rebuildCareSummary(id); await rebuildCareSummary(id);
  assert.equal((await plant.get()).data().careSummary.watering.id, 'newer');
  await newer.delete(); await rebuildCareSummary(id);
  assert.equal((await plant.get()).data().careSummary.watering.id, 'older');
  await older.update({ type: 'note' }); await rebuildCareSummary(id);
  assert.equal((await plant.get()).data().careSummary.watering, null);
  await plant.delete(); await rebuildCareSummary(id); assert.equal((await plant.get()).exists, false);
  const garden = db.doc(`groups/${id}`); const pin = { lat: -33, lng: 18 };
  await garden.set({ location: pin, locationLabel: 'Disposable', createdBy: 'test' });
  let reads = 0;
  const provider = async () => { reads++; return { ok: true, json: async () => ({ current: { dt: Math.floor(Date.now()/1000), temp: 24, humidity: 55, wind_speed: 2, uvi: 3 }, timezone: 'UTC', timezone_offset: 0 }) }; };
  await collectGardenWeather(id, 'test-only', provider);
  const weather = (await garden.get()).data().currentWeather;
  assert.equal(weather.temperature, 24); assert.deepEqual(weather.sourceCoordinates, pin);
  await collectGardenWeather(id, 'test-only', provider); assert.equal(reads, 1, 'Fresh conditions avoid provider calls');
  await garden.update({ currentWeather: null });
  await collectGardenWeather(id, 'test-only', async () => { await garden.update({ location: { lat: -34, lng: 19 } }); return provider(); });
  assert.equal((await garden.get()).data().currentWeather, null, 'A moved pin rejects in-flight conditions');
  await collectGardenWeather(id, 'test-only', provider);
  assert.equal((await garden.get()).data().currentWeather.previousLocations.length, 1, 'Same-day history retains the old pin');
  await garden.update({ deleting: true, currentWeather: null });
  const before = reads; await collectGardenWeather(id, 'test-only', provider); assert.equal(reads, before);
  console.log('PASS: summary initialization, duplicate rebuilds, undo/type correction, deleted parents, scheduled weather freshness, moved-pin races and preserved history.');
})().then(() => process.exit(0), error => { console.error(error); process.exit(1); });
